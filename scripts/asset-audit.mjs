import { createHash } from 'node:crypto';
import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve('public');
const maxRecommendedBytes = 1024 * 1024;
const mediaExtensions = new Set(['.avif', '.gif', '.jpeg', '.jpg', '.mp3', '.mp4', '.png', '.svg', '.webp', '.woff', '.woff2']);
const files = [];

async function walk(directory) {
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') return;
    throw error;
  }
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) await walk(absolute);
    else if (mediaExtensions.has(path.extname(entry.name).toLowerCase())) {
      const metadata = await stat(absolute);
      const content = await readFile(absolute);
      files.push({
        path: path.relative(process.cwd(), absolute).split(path.sep).join('/'),
        bytes: metadata.size,
        hash: createHash('sha256').update(content).digest('hex'),
      });
    }
  }
}

await walk(root);
files.sort((a, b) => b.bytes - a.bytes);
const totalBytes = files.reduce((sum, file) => sum + file.bytes, 0);
const oversized = files.filter((file) => file.bytes > maxRecommendedBytes);
const duplicateGroups = new Map();
for (const file of files) {
  const group = duplicateGroups.get(file.hash) ?? [];
  group.push(file);
  duplicateGroups.set(file.hash, group);
}
const duplicates = [...duplicateGroups.values()].filter((group) => group.length > 1);
const formatBytes = (bytes) => bytes >= 1024 * 1024
  ? `${(bytes / (1024 * 1024)).toFixed(2)} MiB`
  : `${(bytes / 1024).toFixed(1)} KiB`;
const rows = files.slice(0, 25).map((file) => `| ${file.path.replaceAll('|', '\\|')} | ${formatBytes(file.bytes)} |`).join('\\n');
const duplicateRows = duplicates.map((group) => {
  const paths = group.map((file) => file.path).join(', ');
  return `| ${group.length} | ${formatBytes(group[0].bytes)} | ${paths.replaceAll('|', '\\|')} |`;
}).join('\\n');
const report = [
  '# Static Asset Audit',
  '',
  '> Generated by CI. This report is observational only; it does not rewrite or delete source artwork.',
  '',
  `- Files scanned: **${files.length}**`,
  `- Total media bytes: **${formatBytes(totalBytes)}**`,
  `- Files above 1 MiB: **${oversized.length}**`,
  `- Exact duplicate groups: **${duplicates.length}**`,
  '',
  '## Largest assets',
  '',
  '| File | Size |',
  '| --- | ---: |',
  rows || '| No media assets found | — |',
  '',
  '## Exact duplicate content',
  '',
  '| Copies | Per-file size | Paths |',
  '| ---: | ---: | --- |',
  duplicateRows || '| — | — | No exact duplicates found |',
  '',
  '## Optimization guidance',
  '',
  '- Convert photographic and large raster assets to responsive AVIF/WebP variants after visual review.',
  '- Keep transparent logos and typography artwork in a lossless format where edge quality matters.',
  '- Review duplicate copies before removing anything; some paths may be referenced by legacy pages.',
  '- Treat the 1 MiB threshold as a review signal, not a hard failure or universal image-size target.',
  '',
].join('\\n');
await writeFile('asset-audit.md', report);
console.log(`Audited ${files.length} public media files (${formatBytes(totalBytes)} total); ${oversized.length} exceed 1 MiB; ${duplicates.length} exact duplicate groups.`);
